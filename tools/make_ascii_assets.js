// Generates the ASCII Art site assets from Walker's pattern engine (context/brand-ascii.md), in headless Chromium.
//   site/assets/ascii-hero.json    brightness field sampled from the engine's `terrain` render (exact brief call and INKS)
//   site/assets/band-gradpanes.svg renderSVG('gradpanes', ...) with preserveAspectRatio slice
//   site/assets/tile-halftone.svg  tileSVG('halftone', ..., 160)
// Usage: node tools/make_ascii_assets.js [outdir]      (default: site/assets)
// Needs playwright-core (PLAYWRIGHT_CORE env, default ~/Desktop/helix-crm/node_modules/playwright-core) and Chrome (CHROME env).
const fs = require('fs'), path = require('path');
const { chromium } = require(process.env.PLAYWRIGHT_CORE || path.join(process.env.HOME, 'Desktop/helix-crm/node_modules/playwright-core'));
const BASE = path.join(process.env.HOME, 'Desktop/Branding Designer/js/patterns');
const ORDER = ['engine.js', 'families/field.js', 'families/stripe.js', 'families/grid.js', 'families/texture.js', 'families/print2.js', 'families/op2.js', 'families/pixel2.js', 'families/organic2.js', 'families/glitch2.js', 'families/collage2.js', 'fit.js'];
const COLS = 240, ROWS = 68;       // source grid: cell aspect 0.6 : 1.14 (JetBrains Mono), so 240 x 68 is about 1.9 : 1
const CELL_ASPECT = 0.6 / 1.14;
(async () => {
  const out = process.argv[2] || path.join(__dirname, '..', 'site', 'assets');
  const b = await chromium.launch({ executablePath: process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const p = await (await b.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1 })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await p.setContent('<!doctype html><html><body></body></html>');
  for (const f of ORDER) await p.addScriptTag({ content: fs.readFileSync(path.join(BASE, f), 'utf8') });
  const res = await p.evaluate(({ COLS, ROWS, CELL_ASPECT }) => {
    const P = window.Patterns;
    const INKS = P.inksFor({ "canvas": "#1c2126", "ink": "#f5f7f9", "primary": "#7db7eb", "secondary": "#f0c5c6", "accent": "#f0ec5e" }, "brand", { "tints": false });
    // terrain, exact brief call, PNG 2x, on a canvas whose aspect matches the character grid
    const W = 1280;
    const c = document.createElement('canvas');
    const r = P.render(c, 'terrain', { "levels": 6, "pix": 0.5, "dither": 0.6, "style": "hills", "scale": 1, "grain": 0.08, "tints": false, "tone": 1 }, INKS, 'brand', { width: W, height: Math.round(W * (ROWS * 1.14) / (COLS * 0.6)), dpr: 2 });
    const ctx = c.getContext('2d'), data = ctx.getImageData(0, 0, r.w, r.h).data;
    // box-average luminance per character cell
    const lum = new Float64Array(COLS * ROWS);
    for (let cy = 0; cy < ROWS; cy++) for (let cx = 0; cx < COLS; cx++) {
      const x0 = Math.floor(cx * r.w / COLS), x1 = Math.floor((cx + 1) * r.w / COLS), y0 = Math.floor(cy * r.h / ROWS), y1 = Math.floor((cy + 1) * r.h / ROWS);
      let s = 0, n = 0;
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) { const i = (y * r.w + x) * 4; s += (0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]) / 255; n++; }
      lum[cy * COLS + cx] = s / Math.max(n, 1);
    }
    // stretch to 0..9 by percentile so the ramp is fully used whatever the render's tonal range
    const sorted = Array.from(lum).sort((a, z) => a - z), lo = sorted[Math.floor(sorted.length * 0.02)], hi = sorted[Math.floor(sorted.length * 0.995)];
    const rows = [];
    for (let cy = 0; cy < ROWS; cy++) { let s = ''; for (let cx = 0; cx < COLS; cx++) { const v = Math.max(0, Math.min(1, (lum[cy * COLS + cx] - lo) / (hi - lo || 1))); s += String(Math.min(9, Math.floor(v * 10))); } rows.push(s); }
    return {
      inks: INKS, rows, png: [r.w, r.h],
      gradpanes: P.renderSVG('gradpanes', { "rows": 3, "cols": 3, "gap": 1.6, "steps": 0, "radius": 3, "scale": 1, "grain": 0.1, "tints": false, "tone": 1 }, INKS, 'brand', { width: 1200, height: 675 }),
      halftone: P.tileSVG('halftone', { "cell": 1.7, "levels": 5, "shape": "round", "angle": 15, "field": "clouds", "duo": true, "scale": 1, "grain": 0.18, "tints": false, "tone": 1 }, INKS, 'brand', 160)
    };
  }, { COLS, ROWS, CELL_ASPECT });
  console.log('inks', JSON.stringify(res.inks), 'terrain px', res.png.join('x'));
  const hero = {
    note: 'Brightness 0-9 per character cell, box-averaged from Patterns.render("terrain", ...) (context/brand-ascii.md). Generated by tools/make_ascii_assets.js.',
    ramp: ' .:-=+*#%@', cols: COLS, rows: ROWS, field: res.rows
  };
  fs.writeFileSync(path.join(out, 'ascii-hero.json'), JSON.stringify(hero));
  console.log('ascii-hero.json', fs.statSync(path.join(out, 'ascii-hero.json')).size);
  let gp = res.gradpanes;
  gp = /preserveAspectRatio/.test(gp.slice(0, 400)) ? gp.replace(/preserveAspectRatio="[^"]*"/, 'preserveAspectRatio="xMidYMid slice"') : gp.replace(/<svg\b/, '<svg preserveAspectRatio="xMidYMid slice"');
  fs.writeFileSync(path.join(out, 'band-gradpanes.svg'), gp); console.log('band-gradpanes.svg', gp.length);
  fs.writeFileSync(path.join(out, 'tile-halftone.svg'), res.halftone); console.log('tile-halftone.svg', res.halftone.length);
  console.log('errors', errs);
  await b.close();
})();
